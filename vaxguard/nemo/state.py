# ─── Event Enums & Contracts ──────────────────────────────────────────────────

class EventType(str, Enum):
    """Categorization of dialogue state events."""
    USER_SAID = "user_said"
    BOT_SAID = "bot_said"
    USER_INTENT = "user_intent"
    BOT_INTENT = "bot_intent"
    START_ACTION = "start_action"
    ACTION_FINISHED = "action_finished"
    FLOW_STARTED = "flow_started"
    FLOW_COMPLETED = "flow_completed"
    CONTEXT_UPDATED = "context_updated"
    SECURITY_ALERT = "security_alert"
    BRANCH_FORKED = "branch_forked"
    BRANCH_COMMITTED = "branch_committed"
    BRANCH_ROLLBACK = "branch_rollback"
    CUSTOM = "custom"


class Event(BaseModel):
    """Immutable audit record representing a discrete state transition event."""
    event_id: str = Field(default_factory=lambda: str(uuid.uuid4())[:8])
    event_type: EventType
    timestamp: float = Field(default_factory=time.time)
    sender: str = "system"
    data: Dict[str, Any] = Field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "event_id": self.event_id,
            "event_type": self.event_type.value,
            "timestamp": self.timestamp,
            "sender": self.sender,
            "data": self.data,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> Event:
        return cls(
            event_id=data.get("event_id", str(uuid.uuid4())[:8]),
            event_type=EventType(data.get("event_type", "custom")),
            timestamp=data.get("timestamp", time.time()),
            sender=data.get("sender", "system"),
            data=data.get("data", {}),
        )


class EventStack:
    """Chronologically ordered collection of events with filtering and slicing."""

    def __init__(self, events: Optional[List[Event]] = None) -> None:
        self._events: List[Event] = list(events or [])

    def __len__(self) -> int:
        return len(self._events)

    def __iter__(self) -> Iterator[Event]:
        return iter(self._events)

    def push(self, event: Event) -> None:
        """Append event to the stack."""
        self._events.append(event)

    def pop(self) -> Optional[Event]:
        """Pop the most recent event."""
        return self._events.pop() if self._events else None

    def peek(self) -> Optional[Event]:
        """Inspect the most recent event without removing it."""
        return self._events[-1] if self._events else None

    def filter_by_type(self, event_type: EventType) -> List[Event]:
        """Retrieve all events matching the specified type."""
        return [e for e in self._events if e.event_type == event_type]

    def filter_by_sender(self, sender: str) -> List[Event]:
        """Retrieve all events generated by the specified sender."""
        return [e for e in self._events if e.sender == sender]

    def last(self, event_type: Optional[EventType] = None) -> Optional[Event]:
        """Return the most recent event, optionally filtered by type."""
        if event_type is None:
            return self.peek()
        for e in reversed(self._events):
            if e.event_type == event_type:
                return e
        return None

    def slice_recent(self, count: int) -> List[Event]:
        """Get the last N events."""
        return self._events[-count:] if count > 0 else []

    def clear(self) -> None:
        """Clear all events."""
        self._events.clear()

    def to_list(self) -> List[Dict[str, Any]]:
        """Serialize event stack to raw dictionaries."""
        return [e.to_dict() for e in self._events]


# ─── Hierarchical Variable Scopes ─────────────────────────────────────────────

class ScopeLevel(str, Enum):
    """Scope hierarchy hierarchy levels."""
    GLOBAL = "global"
    SESSION = "session"
    FLOW = "flow"
    STEP = "step"


class VariableScope:
    """Hierarchical lexical variable scope with inheritance and shadowing."""

    def __init__(
        self,
        level: ScopeLevel = ScopeLevel.SESSION,
        parent: Optional[VariableScope] = None,
        name: str = "default_scope",
    ) -> None:
        self.level = level
        self.parent = parent
        self.name = name
        self._variables: Dict[str, Any] = {}
        self._ttls: Dict[str, float] = {}

    def get(self, name: str, default: Any = None) -> Any:
        """Resolve variable looking up the lexical scope chain."""
        # Check if local variable is expired
        if name in self._variables:
            if name in self._ttls and time.time() > self._ttls[name]:
                del self._variables[name]
                del self._ttls[name]
            else:
                return self._variables[name]

        # Recurse up scope chain
        if self.parent is not None:
            return self.parent.get(name, default)

        return default

    def set(
        self,
        name: str,
        value: Any,
        local_only: bool = False,
        ttl_seconds: Optional[float] = None,
    ) -> None:
        """Assign variable value. If local_only is False and exists in parent, parent is updated."""
        if not local_only and self.parent is not None and self.parent.has(name):
            self.parent.set(name, value, local_only=False, ttl_seconds=ttl_seconds)
            return

        self._variables[name] = value
        if ttl_seconds is not None:
            self._ttls[name] = time.time() + ttl_seconds
        elif name in self._ttls:
            del self._ttls[name]

    def has(self, name: str) -> bool:
        """Check if variable exists in this scope or any ancestor."""
        if name in self._variables:
            if name in self._ttls and time.time() > self._ttls[name]:
                del self._variables[name]
                del self._ttls[name]
                return False
            return True
        return self.parent.has(name) if self.parent is not None else False

    def delete(self, name: str) -> bool:
        """Delete variable from local scope."""
        removed = self._variables.pop(name, None) is not None
        self._ttls.pop(name, None)
        return removed

    def all_variables(self) -> Dict[str, Any]:
        """Return flattened dictionary of all visible variables in scope chain."""
        result: Dict[str, Any] = {}
        if self.parent is not None:
            result.update(self.parent.all_variables())
        now = time.time()
        for k, v in self._variables.items():
            if k in self._ttls and now > self._ttls[k]:
                continue
            result[k] = v
        return result

    def fork(self, name: Optional[str] = None) -> VariableScope:
        """Fork a child scope linked to this scope."""
        child = VariableScope(
            level=ScopeLevel.STEP if self.level == ScopeLevel.FLOW else ScopeLevel.FLOW,
            parent=self,
            name=name or f"{self.name}_child",
        )
        return child


# ─── Branching Memory & Speculative Execution ─────────────────────────────────

class DialogueBranch:
    """Isolated execution branch allowing speculative evaluation and rollback."""

    def __init__(
        self,
        branch_id: str,
        parent_id: Optional[str] = None,
        event_stack: Optional[EventStack] = None,
        scope: Optional[VariableScope] = None,
    ) -> None:
        self.branch_id = branch_id
        self.parent_id = parent_id
        self.events = event_stack or EventStack()
        self.scope = scope or VariableScope()
        self.active_flows: List[str] = []
        self.created_at = time.time()
        self.is_active: bool = True

    def clone(self, new_branch_id: str) -> DialogueBranch:
        """Create a deep copy for speculative exploration."""
        new_events = EventStack([copy.deepcopy(e) for e in self.events])
        new_scope = VariableScope(
            level=self.scope.level,
            parent=self.scope.parent,
            name=f"{self.scope.name}_fork",
        )
        new_scope._variables = copy.deepcopy(self.scope._variables)
        new_scope._ttls = copy.deepcopy(self.scope._ttls)

        new_branch = DialogueBranch(
            branch_id=new_branch_id,
            parent_id=self.branch_id,
            event_stack=new_events,
            scope=new_scope,
        )
        new_branch.active_flows = list(self.active_flows)
        return new_branch


class BranchingMemoryBuffer:
    """Manages tree of tentative dialogue states for rollback and transaction isolation."""

    def __init__(self, root_session_id: str = "main") -> None:
        self.root_id = root_session_id
        self._branches: Dict[str, DialogueBranch] = {}
        self._active_branch_id = root_session_id

        # Initialize root branch
        root = DialogueBranch(branch_id=root_session_id)
        self._branches[root_session_id] = root

    @property
    def active_branch(self) -> DialogueBranch:
        return self._branches[self._active_branch_id]

    def fork_branch(self, branch_name: Optional[str] = None) -> str:
        """Fork current active branch for speculative evaluation."""
        new_id = branch_name or f"branch_{uuid.uuid4().hex[:6]}"
        cloned = self.active_branch.clone(new_id)
        self._branches[new_id] = cloned
        self._branches[self._active_branch_id].events.push(
            Event(
                event_type=EventType.BRANCH_FORKED,
                sender="memory_manager",
                data={"child_branch_id": new_id},
            )
        )
        return new_id

    def switch_branch(self, branch_id: str) -> bool:
        """Switch active pointer to another existing branch."""
        if branch_id in self._branches:
            self._active_branch_id = branch_id
            return True
        return False

    def commit_branch(self, branch_id: str) -> bool:
        """Merge speculative branch state into its parent and make parent active."""
        if branch_id not in self._branches:
            return False
        child = self._branches[branch_id]
        if not child.parent_id or child.parent_id not in self._branches:
            return False

        parent = self._branches[child.parent_id]
        # Append events from child
        for event in child.events:
            parent.events.push(event)
        # Merge variables
        parent.scope._variables.update(child.scope._variables)
        parent.active_flows = list(child.active_flows)

        parent.events.push(
            Event(
                event_type=EventType.BRANCH_COMMITTED,
                sender="memory_manager",
                data={"committed_branch_id": branch_id},
            )
        )

        # Deactivate child and return to parent
        child.is_active = False
        self._active_branch_id = parent.branch_id
        return True

    def rollback_branch(self, branch_id: str) -> bool:
        """Discard speculative branch and revert active branch to its parent."""
        if branch_id not in self._branches:
            return False
        branch = self._branches[branch_id]
        parent_id = branch.parent_id or self.root_id

        branch.is_active = False
        if branch_id == self._active_branch_id:
            self._active_branch_id = parent_id

        if parent_id in self._branches:
            self._branches[parent_id].events.push(
                Event(
                    event_type=EventType.BRANCH_ROLLBACK,
                    sender="memory_manager",
                    data={"discarded_branch_id": branch_id},
                )
            )
        return True


# ─── Multi-Turn Dialogue State Tracker ────────────────────────────────────────

class DialogueTurn(BaseModel):
    """Encapsulation of a single conversational turn."""
    turn_index: int
    user_message: str
    bot_response: Optional[str] = None
    user_intent: Optional[str] = None
    bot_intent: Optional[str] = None
    triggered_rails: List[str] = Field(default_factory=list)
    actions_invoked: List[str] = Field(default_factory=list)
    timestamp: float = Field(default_factory=time.time)
    metadata: Dict[str, Any] = Field(default_factory=dict)


class StateTracker:
    """Primary state tracking engine maintaining multi-turn context and flow stacks."""

    def __init__(self, session_id: Optional[str] = None) -> None:
        self.session_id: str = session_id or f"sess_{uuid.uuid4().hex[:8]}"
        self.memory = BranchingMemoryBuffer(root_session_id=self.session_id)
        self.flow_stack: List[str] = []
        self._turns: List[DialogueTurn] = []
        self._turn_counter: int = 0
        self.created_at = time.time()
        self.crescendo_defense = CrescendoDefenseEngine()

    @property
    def current_flow(self) -> Optional[str]:
        return self.flow_stack[-1] if self.flow_stack else None

    @property
    def active_scope(self) -> VariableScope:
        return self.memory.active_branch.scope

    @property
    def event_stack(self) -> EventStack:
        return self.memory.active_branch.events

    # ─── Flow Stack Management ────────────────────────────────────────────────

    def push_flow(self, flow_name: str) -> None:
        """Push a newly entered flow onto the active flow stack."""
        self.flow_stack.append(flow_name)
        self.event_stack.push(
            Event(
                event_type=EventType.FLOW_STARTED,
                sender="flow_engine",
                data={"flow_name": flow_name, "depth": len(self.flow_stack)},
            )
        )

    def pop_flow(self) -> Optional[str]:
        """Pop the completed flow from stack."""
        if not self.flow_stack:
            return None
        popped = self.flow_stack.pop()
        self.event_stack.push(
            Event(
                event_type=EventType.FLOW_COMPLETED,
                sender="flow_engine",
                data={"flow_name": popped, "depth": len(self.flow_stack)},
            )
        )
        return popped

    # ─── Turn Lifecycle Tracking ──────────────────────────────────────────────

    def record_user_turn(
        self,
        text: str,
        intent: Optional[str] = None,
        metadata: Optional[Dict[str, Any]] = None,
        matcher_confidence: float = 0.0,
    ) -> DialogueTurn:
        """Record an incoming user utterance, update crescendo risk, and advance the turn counter."""
        self._turn_counter += 1
        turn_meta = dict(metadata or {})

        # Evaluate crescendo cognitive drift and multi-turn boundary erosion
        crescendo_signal = self.crescendo_defense.evaluate_turn(
            turn_index=self._turn_counter,
            prompt=text,
            matcher_confidence=matcher_confidence,
        )
        turn_meta["crescendo"] = crescendo_signal.model_dump()

        turn = DialogueTurn(
            turn_index=self._turn_counter,
            user_message=text,
            user_intent=intent,
            metadata=turn_meta,
        )
        self._turns.append(turn)

        self.event_stack.push(
            Event(
                event_type=EventType.USER_SAID,
                sender="user",
                data={"turn": self._turn_counter, "text": text},
            )
        )
        if intent:
            self.event_stack.push(
                Event(
                    event_type=EventType.USER_INTENT,
                    sender="intent_classifier",
                    data={"turn": self._turn_counter, "intent": intent},
                )
            )

        if crescendo_signal.interception_triggered:
            self.event_stack.push(
                Event(
                    event_type=EventType.SECURITY_ALERT,
                    sender="crescendo_defense",
                    data={
                        "turn": self._turn_counter,
                        "session_risk": crescendo_signal.accumulated_session_risk,
                        "action": "crescendo_interception",
                        "coaxing_markers": crescendo_signal.coaxing_markers_detected,
                    },
                )
            )

        return turn

    def get_session_risk(self) -> float:
        """Return current cumulative session risk score (0.0 to 1.0)."""
        return self.crescendo_defense.current_risk_score

    def get_risk_tier(self) -> RiskTier:
        """Return current categorical risk tier (NORMAL, ELEVATED, CRITICAL)."""
        score = self.crescendo_defense.current_risk_score
        if score >= self.crescendo_defense.critical_threshold:
            return RiskTier.CRITICAL
        elif score >= self.crescendo_defense.elevated_threshold:
            return RiskTier.ELEVATED
        return RiskTier.NORMAL

    def get_effective_threshold(self, base_threshold: float = 0.68) -> float:
        """Return dynamically tightened matcher threshold based on session risk."""
        return self.crescendo_defense.get_effective_threshold(base_threshold)

    def is_crescendo_intercepted(self) -> bool:
        """Check whether the session has crossed into CRITICAL crescendo risk requiring interception."""
        return self.crescendo_defense.current_risk_score >= self.crescendo_defense.critical_threshold

    def record_bot_turn(
        self,
        response_text: str,
        bot_intent: Optional[str] = None,
        triggered_rails: Optional[List[str]] = None,
    ) -> Optional[DialogueTurn]:
        """Record bot response for the current active turn."""
        if not self._turns:
            return None
        current = self._turns[-1]
        current.bot_response = response_text
        current.bot_intent = bot_intent
        if triggered_rails:
            current.triggered_rails.extend(triggered_rails)

        self.event_stack.push(
            Event(
                event_type=EventType.BOT_SAID,
                sender="bot",
                data={"turn": current.turn_index, "text": response_text},
            )
        )
        return current

    def record_action_execution(
        self,
        action_name: str,
        arguments: Dict[str, Any],
        result_value: Any,
        latency_ms: float,
    ) -> None:
        """Audit an executed custom action."""
        if self._turns:
            self._turns[-1].actions_invoked.append(action_name)

        self.event_stack.push(
            Event(
                event_type=EventType.ACTION_FINISHED,
                sender="action_runtime",
                data={
                    "action_name": action_name,
                    "args": arguments,
                    "result": str(result_value)[:200],
                    "latency_ms": latency_ms,
                },
            )
        )

    # ─── Context & History Extraction ─────────────────────────────────────────

    def get_context(self) -> Dict[str, Any]:
        """Flatten current visible context variables and turn indicators."""
        ctx = self.active_scope.all_variables()
        ctx["session_id"] = self.session_id
        ctx["turn_index"] = self._turn_counter
        ctx["current_flow"] = self.current_flow
        if self._turns:
            ctx["last_user_message"] = self._turns[-1].user_message
            ctx["last_bot_response"] = self._turns[-1].bot_response
        return ctx

    def get_recent_history(self, max_turns: int = 5) -> List[Dict[str, str]]:
        """Format recent turns as standard chat role message dicts."""
        history: List[Dict[str, str]] = []
        recent_turns = self._turns[-max_turns:] if max_turns > 0 else self._turns

        for turn in recent_turns:
            history.append({"role": "user", "content": turn.user_message})
            if turn.bot_response:
                history.append({"role": "assistant", "content": turn.bot_response})

        return history

    def get_all_turns(self) -> List[DialogueTurn]:
        """Retrieve full sequence of dialogue turns."""
        return list(self._turns)

    # ─── State Serialization & Diffs ─────────────────────────────────────────

    def to_dict(self) -> Dict[str, Any]:
        """Serialize state tracker for cross-process persistence or REST APIs."""
        return {
            "session_id": self.session_id,
            "turn_counter": self._turn_counter,
            "created_at": self.created_at,
            "flow_stack": list(self.flow_stack),
            "variables": self.active_scope.all_variables(),
            "turns": [t.model_dump() for t in self._turns],
            "events": self.event_stack.to_list(),
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> StateTracker:
        """Instantiate state tracker from serialized dictionary."""
        tracker = cls(session_id=data.get("session_id"))
        tracker._turn_counter = data.get("turn_counter", 0)
        tracker.created_at = data.get("created_at", time.time())
        tracker.flow_stack = list(data.get("flow_stack", []))

        # Restore variables
        for k, v in data.get("variables", {}).items():
            tracker.active_scope.set(k, v)

        # Restore turns
        for turn_data in data.get("turns", []):
            tracker._turns.append(DialogueTurn(**turn_data))

        # Restore events
        for ev_data in data.get("events", []):
            tracker.event_stack.push(Event.from_dict(ev_data))

        return tracker

    def to_json(self) -> str:
        """Serialize state tracker to JSON string."""
        return json.dumps(self.to_dict())

    @classmethod
    def from_json(cls, json_str: str) -> StateTracker:
        """Deserialize state tracker from JSON string."""
        return cls.from_dict(json.loads(json_str))

    def diff_state(self, other: StateTracker) -> Dict[str, Any]:
        """Calculate telemetry diff between this state and another state."""
        this_vars = self.active_scope.all_variables()
        other_vars = other.active_scope.all_variables()

        changed_vars = {
            k: {"from": this_vars.get(k), "to": other_vars.get(k)}
            for k in set(this_vars.keys()) | set(other_vars.keys())
            if this_vars.get(k) != other_vars.get(k)
        }

        return {
            "turn_delta": other._turn_counter - self._turn_counter,
            "flow_stack_changed": self.flow_stack != other.flow_stack,
            "changed_variables": changed_vars,
            "new_events_count": len(other.event_stack) - len(self.event_stack),
        }
