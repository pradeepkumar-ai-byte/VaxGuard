"""
Production-Grade Asynchronous Guardrails Server for VaxGuard.

Provides REST and SSE endpoints matching NVIDIA NeMo Guardrails server architecture:
- /v1/guardrails/generate: End-to-end LLMRails generation with inline guardrails
- /v1/guardrails/evaluate: Sub-millisecond front-line evaluation (TriHybridMatcher)
- /v1/guardrails/retrieval: RAG context chunk inspection & sanitization (RetrievalRail)
- /v1/guardrails/tools/validate: Execution rail sandbox validation for tool calls
- /v1/admin/reload: Live hot-reload of external YAML rules without service restart
- /metrics: Prometheus-compatible telemetry metrics
- /health: Service health and rule inventory status
"""

from __future__ import annotations

import time
from contextlib import asynccontextmanager
from typing import Any, Dict, List, Optional
from fastapi import FastAPI, HTTPException, Response
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

from vaxguard import __version__
from vaxguard.core.logger import get_logger
from vaxguard.core.llm_adapters import MockLLMAdapter
from vaxguard.nemo.hybrid_matcher import TriHybridMatcher
from vaxguard.nemo.retrieval_rail import RetrievalRail
from vaxguard.nemo.execution_rail import ExecutionRail
from vaxguard.integrations.nemo_compat import LLMRails, RailsConfig

logger = get_logger("GuardrailsServer")

# ─── Global Server Singletons ─────────────────────────────────────────────────

_matcher: Optional[TriHybridMatcher] = None
_retrieval_rail: Optional[RetrievalRail] = None
_execution_rail: Optional[ExecutionRail] = None
_rails: Optional[LLMRails] = None

_metrics = {
    "requests_total": 0,
    "evaluations_total": 0,
    "generations_total": 0,
    "blocks_total": 0,
    "retrieval_inspections_total": 0,
    "tool_validations_total": 0,
    "reloads_total": 0,
}


@asynccontextmanager
async def lifespan(app: FastAPI):
    global _matcher, _retrieval_rail, _execution_rail, _rails
    logger.info("Initializing VaxGuard Guardrails Engine Server...")

    _matcher = TriHybridMatcher()
    _retrieval_rail = RetrievalRail(matcher=_matcher)
    _execution_rail = ExecutionRail()

    adapter = MockLLMAdapter(
        default_response="Safe response generated by VaxGuard protected engine.",
        artificial_latency_ms=10.0,
    )
    config = RailsConfig()
    _rails = LLMRails(
        config=config,
        llm_adapter=adapter,
        matcher=_matcher,
        retrieval_rail=_retrieval_rail,
        execution_rail=_execution_rail,
    )

    logger.info(f"Guardrails Engine online. Patterns active: {len(_matcher.patterns)}")
    yield
    logger.info("Guardrails Engine Server shutting down...")


app = FastAPI(
    title="VaxGuard Production Guardrails Server",
    description="Drop-in Replacement for NeMo Guardrails with Ultra-Low-Latency Filtering, RAG Inspection, and Tool Sandboxing.",
    version=__version__,
    lifespan=lifespan,
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


# ─── Request & Response Models ────────────────────────────────────────────────

class GenerateRequest(BaseModel):
    prompt: str = Field(..., description="User prompt to evaluate and process")
    system_prompt: Optional[str] = Field(None, description="Optional system directive")
    context: Optional[str] = Field(None, description="Optional retrieval context")
    model: Optional[str] = Field(None, description="Model identifier override")
    temperature: Optional[float] = Field(0.7, description="Generation temperature")


class GenerateResponse(BaseModel):
    response: str
    action: str
    blocked: bool
    latency_ms: float
    tokens_consumed: int
    rule_id: Optional[str] = None


class EvaluateRequest(BaseModel):
    prompt: str = Field(..., description="Text payload to evaluate against active guardrail patterns")


class EvaluateResponse(BaseModel):
    matched: bool
    category: str
    rule_id: str
    confidence: float
    action: str
    latency_ms: float


class RetrievalRequest(BaseModel):
    chunks: List[str] = Field(..., description="Retrieved document chunks to inspect")
    policy: str = Field("reject", description="Sanitization policy: 'reject' or 'mask'")


class RetrievalResponse(BaseModel):
    passed: bool
    action: str
    sanitized_chunks: List[str]
    rejected_chunks: List[str]
    violations: List[str]
    latency_ms: float


class ToolValidateRequest(BaseModel):
    tool_name: str = Field(..., description="Name of the tool/function to execute")
    parameters: Dict[str, Any] = Field(default_factory=dict, description="Dictionary of tool arguments")


class ToolValidateResponse(BaseModel):
    allowed: bool
    action: str
    blocked_reasons: List[str]
    risk_level: str
    latency_ms: float


class ReloadResponse(BaseModel):
    success: bool
    reloaded_rules_count: int
    total_patterns: int
    latency_ms: float


# ─── Endpoints ────────────────────────────────────────────────────────────────

@app.get("/health")
async def health():
    global _matcher
    patterns_count = len(_matcher.patterns) if _matcher else 0
    return {
        "status": "healthy",
        "version": __version__,
        "engine": "VaxGuard Enterprise Guardrails",
        "patterns_registered": patterns_count,
        "metrics": _metrics,
    }


@app.post("/v1/guardrails/generate", response_model=GenerateResponse)
async def generate(req: GenerateRequest):
    global _rails, _metrics
    if not _rails:
        raise HTTPException(status_code=503, detail="Rails engine not initialized")

    _metrics["requests_total"] += 1
    _metrics["generations_total"] += 1

    t0 = time.perf_counter()
    resp_text = await _rails.generate_async(prompt=req.prompt, context=req.context)
    elapsed_ms = (time.perf_counter() - t0) * 1000.0

    is_blocked = "I cannot fulfill this request" in resp_text or "blocked" in resp_text.lower()
    explain_info = _rails.explain()
    is_blocked = explain_info.status in ("input_blocked", "output_blocked") or "decline to execute" in resp_text.lower()
    if is_blocked:
        _metrics["blocks_total"] += 1

    tokens = getattr(getattr(_rails, "llm_adapter", None), "last_tokens_consumed", len(resp_text.split()))

    return GenerateResponse(
        response=resp_text,
        action="block" if is_blocked else "allow",
        blocked=is_blocked,
        latency_ms=round(elapsed_ms, 3),
        tokens_consumed=tokens,
        rule_id=explain_info.triggered_rails[0] if explain_info.triggered_rails else None,
    )


@app.post("/v1/guardrails/evaluate", response_model=EvaluateResponse)
async def evaluate(req: EvaluateRequest):
    global _matcher, _metrics
    if not _matcher:
        raise HTTPException(status_code=503, detail="Matcher not initialized")

    _metrics["requests_total"] += 1
    _metrics["evaluations_total"] += 1

    res = _matcher.evaluate(req.prompt)
    if res.matched:
        _metrics["blocks_total"] += 1

    return EvaluateResponse(
        matched=res.matched,
        category=res.category,
        rule_id=res.rule_id,
        confidence=round(res.confidence, 4),
        action=res.action.value if hasattr(res.action, "value") else str(res.action),
        latency_ms=round(res.latency_ms, 3),
    )


@app.post("/v1/guardrails/retrieval", response_model=RetrievalResponse)
async def inspect_retrieval(req: RetrievalRequest):
    global _retrieval_rail, _metrics
    if not _retrieval_rail:
        raise HTTPException(status_code=503, detail="Retrieval rail not initialized")

    _metrics["requests_total"] += 1
    _metrics["retrieval_inspections_total"] += 1

    verdict = await _retrieval_rail.inspect_chunks_async(req.chunks, policy=req.policy)

    return RetrievalResponse(
        passed=verdict.passed,
        action=verdict.action.value if hasattr(verdict.action, "value") else str(verdict.action),
        sanitized_chunks=[c.text for c in verdict.sanitized_chunks],
        rejected_chunks=[c.text for c in verdict.rejected_chunks],
        violations=[f"{v.rule_id}: {v.matched_pattern}" for v in verdict.violations],
        latency_ms=round(verdict.latency_ms, 3),
    )


@app.post("/v1/guardrails/tools/validate", response_model=ToolValidateResponse)
async def validate_tool(req: ToolValidateRequest):
    global _execution_rail, _metrics
    if not _execution_rail:
        raise HTTPException(status_code=503, detail="Execution rail not initialized")

    _metrics["requests_total"] += 1
    _metrics["tool_validations_total"] += 1

    verdict = _execution_rail.validate_tool_call({"name": req.tool_name, "arguments": req.parameters})

    return ToolValidateResponse(
        allowed=verdict.allowed,
        action=verdict.action.value if hasattr(verdict.action, "value") else str(verdict.action),
        blocked_reasons=verdict.violations if verdict.violations else ([verdict.reason] if not verdict.allowed else []),
        risk_level="high" if not verdict.allowed else "low",
        latency_ms=round(verdict.latency_ms, 3),
    )


@app.post("/v1/admin/reload", response_model=ReloadResponse)
async def reload_rules():
    global _matcher, _metrics
    if not _matcher:
        raise HTTPException(status_code=503, detail="Matcher not initialized")

    t0 = time.perf_counter()
    reloaded_count = _matcher.reload_external_rules()
    elapsed_ms = (time.perf_counter() - t0) * 1000.0

    _metrics["reloads_total"] += 1

    return ReloadResponse(
        success=True,
        reloaded_rules_count=reloaded_count,
        total_patterns=len(_matcher.patterns),
        latency_ms=round(elapsed_ms, 3),
    )


