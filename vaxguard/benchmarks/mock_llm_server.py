"""
Mock LLM Server and End-to-End Performance Benchmark Harness.

Matches NVIDIA NeMo Guardrails' `benchmark/mock_llm_server` architecture.
Provides an OpenAI-compatible HTTP server with deterministic token generation,
configurable artificial latency, and a concurrent load-testing harness to
measure end-to-end P50/P95/P99 latency and QPS overhead.
"""

from __future__ import annotations

import argparse
import asyncio
import time
from dataclasses import dataclass, field
from typing import Any, List, Optional
import uvicorn
from fastapi import FastAPI
from pydantic import BaseModel

from vaxguard.core.logger import get_logger

logger = get_logger("MockLLMServer")


# ─── FastAPI Server Definition ────────────────────────────────────────────────

class ChatMessage(BaseModel):
    role: str
    content: str


class ChatCompletionRequest(BaseModel):
    model: str = "mock-model"
    messages: List[ChatMessage]
    temperature: Optional[float] = 0.7
    max_tokens: Optional[int] = 256
    stream: Optional[bool] = False


class CompletionRequest(BaseModel):
    model: str = "mock-model"
    prompt: str
    max_tokens: Optional[int] = 256
    stream: Optional[bool] = False


def create_mock_llm_app(
    artificial_latency_ms: float = 10.0,
    default_response: str = "This is a safe, validated response generated by the Mock LLM server.",
) -> FastAPI:
    """Creates a FastAPI application simulating an OpenAI-compatible LLM endpoint."""
    app = FastAPI(title="VaxGuard Mock LLM Server", version="1.0.0")
    request_counter = {"total": 0, "tokens": 0}

    @app.get("/health")
    async def health():
        return {
            "status": "healthy",
            "server": "vaxguard-mock-llm",
            "artificial_latency_ms": artificial_latency_ms,
            "requests_served": request_counter["total"],
        }

    @app.get("/stats")
    async def stats():
        return {
            "total_requests": request_counter["total"],
            "total_tokens": request_counter["tokens"],
        }

    @app.post("/v1/chat/completions")
    async def chat_completions(req: ChatCompletionRequest):
        if artificial_latency_ms > 0:
            await asyncio.sleep(artificial_latency_ms / 1000.0)

        request_counter["total"] += 1
        prompt_tokens = sum(len(m.content.split()) for m in req.messages)
        completion_tokens = len(default_response.split())
        request_counter["tokens"] += (prompt_tokens + completion_tokens)

        return {
            "id": f"chatcmpl-mock-{int(time.time() * 1000)}",
            "object": "chat.completion",
            "created": int(time.time()),
            "model": req.model,
            "choices": [
                {
                    "index": 0,
                    "message": {
                        "role": "assistant",
                        "content": default_response,
                    },
                    "finish_reason": "stop",
                }
            ],
            "usage": {
                "prompt_tokens": prompt_tokens,
                "completion_tokens": completion_tokens,
                "total_tokens": prompt_tokens + completion_tokens,
            },
        }

    @app.post("/v1/completions")
    async def completions(req: CompletionRequest):
        if artificial_latency_ms > 0:
            await asyncio.sleep(artificial_latency_ms / 1000.0)

        request_counter["total"] += 1
        prompt_tokens = len(req.prompt.split())
        completion_tokens = len(default_response.split())
        request_counter["tokens"] += (prompt_tokens + completion_tokens)

        return {
            "id": f"cmpl-mock-{int(time.time() * 1000)}",
            "object": "text_completion",
            "created": int(time.time()),
            "model": req.model,
            "choices": [
                {
                    "index": 0,
                    "text": default_response,
                    "finish_reason": "stop",
                }
            ],
            "usage": {
                "prompt_tokens": prompt_tokens,
                "completion_tokens": completion_tokens,
                "total_tokens": prompt_tokens + completion_tokens,
            },
        }

    return app


# ─── End-to-End Benchmark Harness ─────────────────────────────────────────────

@dataclass
class BenchmarkResult:
    total_requests: int
    successful_requests: int
    blocked_requests: int
    error_count: int
    duration_s: float
    qps: float
    latency_mean_ms: float
    latency_p50_ms: float
    latency_p90_ms: float
    latency_p95_ms: float
    latency_p99_ms: float
    guardrail_overhead_ms: float
    latencies: List[float] = field(default_factory=list)


class MockBenchmarkRunner:
    """
    Concurrent benchmark runner simulating high-throughput client load
    against VaxGuard LLMRails and raw mock LLMs.
    """

    def __init__(
        self,
        concurrency: int = 10,
        requests_count: int = 100,
        mock_latency_ms: float = 15.0,
    ) -> None:
        self.concurrency = concurrency
        self.requests_count = requests_count
        self.mock_latency_ms = mock_latency_ms

    async def run_benchmark(
        self,
        prompts: Optional[List[str]] = None,
        rails_instance: Optional[Any] = None,
    ) -> BenchmarkResult:
        """
        Executes concurrent load test through LLMRails (or direct simulated path).
        """
        if prompts is None:
            prompts = [
                "What is the capital of France?",
                "Explain the time complexity of quicksort in big-O notation.",
                "How do vaccines stimulate adaptive immune memory?",
                "Provide a summary of quarterly revenue growth metrics.",
                "Describe how database indexing improves SQL query performance.",
            ]

        # If rails_instance is not provided, instantiate a lightweight LLMRails with Mock adapter
        if rails_instance is None:
            from vaxguard.integrations.nemo_compat import LLMRails, RailsConfig
            from vaxguard.core.llm_adapters import MockLLMAdapter

            adapter = MockLLMAdapter(
                default_response="Safe verified response from VaxGuard protected engine.",
                artificial_latency_ms=self.mock_latency_ms,
            )
            config = RailsConfig()
            rails_instance = LLMRails(config=config, llm_adapter=adapter)

        semaphore = asyncio.Semaphore(self.concurrency)
        latencies: List[float] = []
        blocked_count = 0
        error_count = 0

        async def worker(index: int):
            nonlocal blocked_count, error_count
            prompt = prompts[index % len(prompts)]
            async with semaphore:
                t0 = time.perf_counter()
                try:
                    if hasattr(rails_instance, "generate_async"):
                        resp = await rails_instance.generate_async(prompt=prompt)
                    else:
                        resp = rails_instance.generate(prompt=prompt)
                    elapsed_ms = (time.perf_counter() - t0) * 1000.0
                    latencies.append(elapsed_ms)
                    if "I cannot fulfill this request" in str(resp) or "blocked" in str(resp).lower():
                        blocked_count += 1
                except Exception as ex:
                    logger.error(f"Benchmark request error: {ex}")
                    error_count += 1

        t_start = time.perf_counter()
        tasks = [worker(i) for i in range(self.requests_count)]
        await asyncio.gather(*tasks)
        total_time_s = max(0.001, time.perf_counter() - t_start)

        # Percentile metrics calculation
        if latencies:
            sorted_lat = sorted(latencies)
            n = len(sorted_lat)
            p50 = sorted_lat[int(0.50 * n)]
            p90 = sorted_lat[min(n - 1, int(0.90 * n))]
            p95 = sorted_lat[min(n - 1, int(0.95 * n))]
            p99 = sorted_lat[min(n - 1, int(0.99 * n))]
            mean_lat = sum(sorted_lat) / n
        else:
            p50 = p90 = p95 = p99 = mean_lat = 0.0

        overhead = max(0.0, mean_lat - self.mock_latency_ms)
        qps = len(latencies) / total_time_s

        return BenchmarkResult(
            total_requests=self.requests_count,
            successful_requests=len(latencies) - error_count,
            blocked_requests=blocked_count,
            error_count=error_count,
            duration_s=round(total_time_s, 3),
            qps=round(qps, 2),
            latency_mean_ms=round(mean_lat, 3),
            latency_p50_ms=round(p50, 3),
            latency_p95_ms=round(p95, 3),
            latency_p90_ms=round(p90, 3),
            latency_p99_ms=round(p99, 3),
            guardrail_overhead_ms=round(overhead, 3),
            latencies=latencies,
        )


def main():
    parser = argparse.ArgumentParser(description="VaxGuard Mock LLM Server & Benchmark")
    parser.add_argument("--host", default="127.0.0.1", help="Host (default: 127.0.0.1)")
    parser.add_argument("--port", type=int, default=8080, help="Port (default: 8080)")
    parser.add_argument("--latency-ms", type=float, default=15.0, help="Artificial latency in ms")
    parser.add_argument("--run-benchmark", action="store_true", help="Execute concurrent benchmark immediately")
    parser.add_argument("--concurrency", type=int, default=10, help="Concurrent workers")
    parser.add_argument("--requests", type=int, default=100, help="Total requests")

    args = parser.parse_args()

    if args.run_benchmark:
        runner = MockBenchmarkRunner(
            concurrency=args.concurrency,
            requests_count=args.requests,
            mock_latency_ms=args.latency_ms,
        )
        print(f"[INFO] Running benchmark: {args.requests} requests @ concurrency={args.concurrency} ...")
        res = asyncio.run(runner.run_benchmark())
        print("\n" + "=" * 55)
        print("[REPORT] VAXGUARD END-TO-END MOCK-LLM BENCHMARK REPORT")
        print("=" * 55)
        print(f"Total Requests:       {res.total_requests}")
        print(f"Duration:             {res.duration_s:.3f} s")
        print(f"Throughput:           {res.qps:.2f} QPS")
        print(f"Mean Latency:         {res.latency_mean_ms:.3f} ms")
        print(f"P50 (Median) Latency: {res.latency_p50_ms:.3f} ms")
        print(f"P95 Latency:          {res.latency_p95_ms:.3f} ms")
        print(f"P99 Latency:          {res.latency_p99_ms:.3f} ms")
        print(f"Guardrail Overhead:   {res.guardrail_overhead_ms:.3f} ms")
        print("=" * 55)
    else:
        app = create_mock_llm_app(artificial_latency_ms=args.latency_ms)
        print(f"[INFO] Launching VaxGuard Mock LLM Server on http://{args.host}:{args.port} (latency={args.latency_ms}ms) ...")
        uvicorn.run(app, host=args.host, port=args.port)


if __name__ == "__main__":
    main()
